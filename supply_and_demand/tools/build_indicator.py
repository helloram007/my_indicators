"""Generate a standalone indicator and an import-based example from one core.
Run from any directory; --check verifies committed generated outputs.
"""
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
lib = (root/'src/HTFStructure.pine').read_text(encoding='utf-8')
view = (root/'src/htf_structure_view.pine.inc').read_text(encoding='utf-8')
core = lib.split('library("HTFStructure", overlay = true)\n', 1)[1].replace('export ', '')
header = '//@version=6\n// GENERATED by tools/build_indicator.py; edit the library/view sources.\nindicator("Supply & Demand - HTF Structure", overlay = true, max_labels_count = 500)\n'
outputs = {
    root/'src/htf_structure.pine': header + core + '\n' + view,
    root/'src/htf_structure_import.pine.example': header + '// Replace username/version after publishing HTFStructure in TradingView.\nimport YOUR_TRADINGVIEW_USERNAME/HTFStructure/1 as structure\n\n' + view.replace('confirmed(leftBars, rightBars)', 'structure.confirmed(leftBars, rightBars)'),
}
for path, content in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit(f'Generated output out of date: {path.name}')
    else:
        path.write_text(content, encoding='utf-8')
print('Generated outputs match sources.' if '--check' in sys.argv else 'Generated standalone indicator and library consumer example.')
